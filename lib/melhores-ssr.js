function renderHall(publishedEditions, guideLookup) {
  const allWinners = publishedEditions.flatMap(({ edition, results }) =>
    results.filter(row => row.vencedor).map(row => ({ ...row, melhores_edicoes: { ano: edition.ano } }))
  );
  const winsByKey = new Map();
  allWinners.forEach(row => {
    const key = row?.melhores_indicados?.guia_comercial_id || row?.indicado_id || "";
    if (!key) return;
    if (!winsByKey.has(key)) winsByKey.set(key, []);
    winsByKey.get(key).push(row);
  });
  let listHtml = '<div class="awards-empty">Ainda não há vencedores publicados. O Hall será aberto após a divulgação oficial dos resultados.</div>';
  if (allWinners.length) {
    const buttons = publishedEditions.map(({ edition }, index) => {
      const thumb = safeMedia(edition.imagem_capa_url || (Number(edition.ano) === 2026 ? "/assets/melhores/hall-2026.png" : "/assets/melhores/simbolo.png"), { width: 160, height: 100, quality: 78 });
      return `<button type="button" data-award-year="${esc(edition.ano)}" aria-controls="award-year-${esc(edition.ano)}" aria-pressed="${index === 0}"><span class="award-year-cover"><img src="${thumb}" alt="${esc(edition.nome)}" width="80" height="50" loading="lazy" decoding="async"></span><span><strong>${esc(edition.ano)}</strong><small>${Number(edition.ano) === 2026 ? "Primeira edição" : esc(edition.nome)}</small></span></button>`;
    }).join("");
    const years = publishedEditions.map(({ edition, results }, index) => {
      const groups = new Map();
      results.forEach(row => {
        if (!groups.has(row.categoria_id)) groups.set(row.categoria_id, []);
        groups.get(row.categoria_id).push(row);
      });
      const categoriesHtml = [...groups.values()].map(rows => {
        const winners = rows.filter(row => row.vencedor);
        const nominees = edition.status === "apuracao" ? [] : rows.filter(row => !row.vencedor);
        return `<section class="award-archive-category"><h3 class="award-archive-label">${esc(rows[0]?.melhores_categorias?.nome || "Categoria")}</h3><div class="award-archive-entries">${winners.map(row => buildWinnerCard(row, winsByKey, edition, guideLookup, true)).join("")}${nominees.length ? `<div class="award-archive-nominees"><h4>Demais indicados</h4><ul>${nominees.map(row => `<li>${esc(row?.melhores_indicados?.nome || row?.melhores_indicados?.guia_comercial?.nome || "Indicado")}</li>`).join("")}</ul></div>` : ""}</div></section>`;
      }).join("");
      return `<section class="awards-hall-year" id="award-year-${esc(edition.ano)}" aria-labelledby="awards-hall-${esc(edition.ano)}"${index ? " hidden" : ""}><header class="awards-hall-year-head"><div><p class="eyebrow">Edição oficial</p><h2 id="awards-hall-${esc(edition.ano)}">${esc(edition.ano)}</h2></div><a class="button button-secondary" href="/melhores-de-urania/${encodeURIComponent(edition.ano)}/resultados/">Ver resultados da edição <span aria-hidden="true">→</span></a></header><div class="award-hall-grid">${categoriesHtml}</div></section>`;
    }).join("");
    listHtml = `<div class="award-year-select" role="group" aria-label="Ano da edição">${buttons}</div>${years}`;
  }

  return `<main id="conteudo"><section class="awards-public-hero"><div class="award-shell awards-public-grid"><div class="awards-public-copy" id="hall-copy" data-server-rendered="true"><span class="awards-public-badge">Histórico oficial</span><h1>Hall dos <em class="award-accent">vencedores</em></h1><p>Revisite quem foi reconhecido em cada edição do Melhores de Urânia.</p><div class="hero-actions"><a class="button button-secondary" href="/melhores-de-urania/">Ver premiação</a></div></div><article class="awards-public-panel" id="hall-panel" data-server-rendered="true"><img src="/assets/melhores/hall-2026.png" width="3510" height="1770" alt="Arte oficial do Prêmio Melhores de Urânia 2026"></article></div></section><section class="awards-section"><div class="award-shell"><header class="awards-section-head"><h2>Edições publicadas</h2></header><div id="hall-list" data-server-rendered="true">${listHtml}</div></div></section></main>`;
}

