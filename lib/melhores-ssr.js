async function renderAwardsSsr({ mode, year, slug, editions, edition, category, rows }) {
  const header = renderHeader(mode, year || edition?.ano || "");
  const safeRows = (table, params) => rows(table, params).catch(() => []);
  const needGuides = ["award-edition", "award-category", "award-results", "award-hall", "award-winner"].includes(mode);
  const guidesPromise = needGuides
    ? safeRows("guia_comercial", { select: "id,slug,nome", status: "eq.publicado" })
    : Promise.resolve([]);

  if (mode === "award-home") {
    const allEditions = editions.length ? editions : await safeRows("melhores_edicoes", {
      select: "id,nome,ano,slug,descricao,imagem_capa_url,status,indicacoes_inicio,indicacoes_fim,votacao_inicio,votacao_inicio_site,votacao_fim,divulgacao_em,resultado_publicado_em",
      status: "in.(indicacoes_abertas,indicacoes_encerradas,votacao_aberta,votacao_encerrada,apuracao,resultado_publicado,arquivada)",
      order: "ano.desc"
    });
    const active = allEditions.find(item => item.status === "indicacoes_abertas" || item.status === "votacao_aberta") || allEditions[0];
    const announcedWinners = active && ["apuracao", "resultado_publicado", "arquivada"].includes(active.status)
      ? (await safeRows("rpc/melhores_listar_resultados_publicos", {
          p_edicao: active.id,
          p_somente_vencedores: "true",
          order: "publicado_em.desc"
        })).filter(row => row.vencedor && row.publicado)
      : [];
    return {
      html: header + renderHome(allEditions, announcedWinners) + FOOTER,
      bootstrap: { mode, editions: allEditions },
      structuredContext: { editions: allEditions }
    };
  }

  if (mode === "award-edition") {
    const [categories, nominees, guides] = await Promise.all([
      edition?.id ? safeRows("melhores_categorias", { select: "id,edicao_id,nome,slug,descricao,imagem_url,ordem,status,permite_indicacao_publica,max_escolhas", edicao_id: `eq.${edition.id}`, order: "ordem.asc,nome.asc" }) : Promise.resolve([]),
      edition?.id ? safeRows("melhores_indicados", { select: "id,edicao_id,categoria_id,nome,slug,imagem_url,descricao_curta,status,ordem,aprovado,guia_comercial_id", edicao_id: `eq.${edition.id}`, order: "ordem.asc,nome.asc" }) : Promise.resolve([]),
      guidesPromise
    ]);
    const lookup = buildGuideLookup(guides);
    return {
      html: header + renderEdition(edition, categories, nominees, lookup) + FOOTER,
      bootstrap: { mode, edition, categories, nominees, guideSlugs: Object.fromEntries(lookup.byId), guideNames: Object.fromEntries(lookup.bySlug) },
      structuredContext: { categories, nominees, guideLookup: lookup }
    };
  }

  if (mode === "award-category") {
    const [nominees, guides] = await Promise.all([
      edition?.id && category?.id ? safeRows("melhores_indicados", { select: "id,edicao_id,categoria_id,nome,slug,imagem_url,descricao_curta,status,ordem,aprovado,guia_comercial_id", edicao_id: `eq.${edition.id}`, categoria_id: `eq.${category.id}`, order: "ordem.asc,nome.asc" }) : Promise.resolve([]),
      guidesPromise
    ]);
    const lookup = buildGuideLookup(guides);
    return {
      html: header + renderCategory(edition, category, nominees, lookup, slug) + FOOTER,
      bootstrap: { mode, edition, category, nominees, guideSlugs: Object.fromEntries(lookup.byId), guideNames: Object.fromEntries(lookup.bySlug) },
      structuredContext: { nominees, guideLookup: lookup }
    };
  }

  if (mode === "award-permanent-category") {
    const historyRows = slug ? await safeRows("melhores_categorias", {
      select: "id,edicao_id,nome,slug,descricao,imagem_url,ordem,status,atualizado_em,melhores_edicoes!inner(id,nome,ano,slug,descricao,imagem_capa_url,status,atualizado_em)",
      slug: `eq.${slug}`,
      "melhores_edicoes.status": "in.(indicacoes_abertas,indicacoes_encerradas,votacao_aberta,votacao_encerrada,apuracao,resultado_publicado,arquivada)",
      order: "atualizado_em.desc"
    }) : [];
    const sorted = [...historyRows].sort((a, b) => Number(b.melhores_edicoes?.ano || 0) - Number(a.melhores_edicoes?.ano || 0));
    return {
      html: header + renderPermanentCategory(sorted) + FOOTER,
      bootstrap: { mode, rows: sorted },
      structuredContext: { historyRows: sorted }
    };
  }

  if (mode === "award-results") {
    const [results, history, guides] = await Promise.all([
      edition?.id ? safeRows("rpc/melhores_listar_resultados_publicos", { p_edicao: edition.id, p_somente_vencedores: "false", order: "categoria_id.asc,colocacao.asc" }) : Promise.resolve([]),
      safeRows("rpc/melhores_listar_resultados_publicos", { p_somente_vencedores: "true", order: "edicao_id.asc,categoria_id.asc" }),
      guidesPromise
    ]);
    const lookup = buildGuideLookup(guides);
    return {
      html: header + renderResults(edition, results, history, lookup, year) + FOOTER,
      bootstrap: { mode, edition, results, history, guideSlugs: Object.fromEntries(lookup.byId), guideNames: Object.fromEntries(lookup.bySlug) },
      structuredContext: { results }
    };
  }

  if (mode === "award-hall") {
    const completeEditions = (editions || [])
      .filter(item => ["apuracao", "resultado_publicado", "arquivada"].includes(item.status))
      .sort((a, b) => Number(b.ano) - Number(a.ano));
    const [loaded, guides] = await Promise.all([
      Promise.all(completeEditions.map(async ed => ({
        edition: ed,
        results: await safeRows("rpc/melhores_listar_resultados_publicos", { p_edicao: ed.id, p_somente_vencedores: "false", order: "categoria_id.asc,colocacao.asc" })
      }))),
      guidesPromise
    ]);
    const published = loaded.filter(item => resultsArePublished(item.edition, item.results));
    const lookup = buildGuideLookup(guides);
    return {
      html: header + renderHall(published, lookup) + FOOTER,
      bootstrap: { mode, published },
      structuredContext: { published }
    };
  }

  if (mode === "award-winner") {
    const [results, history, guides] = await Promise.all([
      edition?.id ? safeRows("rpc/melhores_listar_resultados_publicos", { p_edicao: edition.id, p_somente_vencedores: "false", order: "categoria_id.asc,colocacao.asc" }) : Promise.resolve([]),
      safeRows("rpc/melhores_listar_resultados_publicos", { p_somente_vencedores: "true", order: "edicao_id.asc,categoria_id.asc" }),
      guidesPromise
    ]);
    const published = edition && resultsArePublished(edition, results);
    const winner = published ? results.find(row => row.vencedor && row.indicado_id === slug) : null;
    const lookup = buildGuideLookup(guides);
    return {
      html: header + renderWinner(edition, winner, history, lookup, year, slug) + FOOTER,
      bootstrap: { mode, edition, winner },
      structuredContext: { winner }
    };
  }

  if (mode === "award-rules") {
    return {
      html: header + renderRules(edition, year) + FOOTER,
      bootstrap: { mode, edition }
    };
  }

  if (mode === "award-method") {
    return {
      html: header + renderMethod(edition, year) + FOOTER,
      bootstrap: { mode, edition }
    };
  }

  return null;
}

function buildAwardStructuredData({
  mode,
  year,
  slug,
  editions = [],
  edition,
  category,
  categories = [],
  nominees = [],
  historyRows = [],
  results = [],
  published = [],
  winner,
  guideLookup = { byId: new Map(), bySlug: new Map() },
  title,
  description,
  url,
  image
}) {
  const safeYear = encodeURIComponent(edition?.ano || year || "");
  const canonicalUrl = url || `${DOMAIN}/melhores-de-urania/`;
  const crumbs = [
    ["Início", `${DOMAIN}/`],
    ["Melhores de Urânia", `${DOMAIN}/melhores-de-urania/`]
  ];
  if (mode === "award-hall") {
    crumbs.push(["Hall dos vencedores", canonicalUrl]);
  } else if (mode === "award-permanent-category") {
    crumbs.push([category?.nome || historyRows[0]?.nome || slug || "Categoria", canonicalUrl]);
  } else if (mode !== "award-home" && safeYear) {
    const editionUrl = `${DOMAIN}/melhores-de-urania/${safeYear}/`;
    crumbs.push([edition?.nome || `Edição ${edition?.ano || year}`, editionUrl]);
    if (mode === "award-category") crumbs.push([category?.nome || slug || "Categoria", canonicalUrl]);
    else if (mode === "award-results") crumbs.push(["Resultados", canonicalUrl]);
    else if (mode === "award-rules") crumbs.push(["Regulamento", canonicalUrl]);
    else if (mode === "award-method") crumbs.push(["Metodologia", canonicalUrl]);
    else if (mode === "award-voting") {
      crumbs.push(["Votação", `${editionUrl}votacao/`]);
      if (category?.nome || slug) crumbs.push([category?.nome || slug, canonicalUrl]);
    } else if (mode === "award-winner") {
      crumbs.push(["Resultados", `${editionUrl}resultados/`]);
      crumbs.push([winner?.melhores_indicados?.nome || "Vencedor", canonicalUrl]);
    }
  }

  const breadcrumb = {
    "@type": "BreadcrumbList",
    "@id": `${canonicalUrl}#breadcrumb`,
    itemListElement: crumbs.map(([name, item], index) => ({
      "@type": "ListItem",
      position: index + 1,
      name,
      item
    }))
  };

  let listEntries = [];
  let listName = "";
  if (mode === "award-home" && editions.length) {
    listName = "Edições do Melhores de Urânia";
    listEntries = editions.slice(0, 20).map(item => ({
      name: item.nome || `Melhores de Urânia ${item.ano}`,
      url: `${DOMAIN}/melhores-de-urania/${encodeURIComponent(item.ano)}/`
    }));
  } else if (mode === "award-edition" && categories.length) {
    listName = `Categorias — ${edition?.nome || `Melhores de Urânia ${year}`}`;
    listEntries = categories.slice(0, 40).map(item => ({
      name: item.nome,
      url: `${DOMAIN}/melhores-de-urania/${safeYear}/categorias/${encodeURIComponent(item.slug)}/`
    }));
  } else if (mode === "award-category" && nominees.length) {
    listName = `Indicados — ${category?.nome || slug}`;
    listEntries = nominees.slice(0, 40).map((item, index) => {
      const guidePath = resolveGuideUrl(item, guideLookup);
      return {
        name: item.nome,
        url: guidePath ? `${DOMAIN}${guidePath}` : `${canonicalUrl}#indicado-${index + 1}`
      };
    });
  } else if (mode === "award-permanent-category" && historyRows.length) {
    listName = `Edições da categoria ${category?.nome || historyRows[0]?.nome || slug}`;
    listEntries = historyRows.slice(0, 20).map(row => ({
      name: row.melhores_edicoes?.nome || `${row.nome} ${row.melhores_edicoes?.ano || ""}`.trim(),
      url: `${DOMAIN}/melhores-de-urania/${encodeURIComponent(row.melhores_edicoes?.ano || "")}/categorias/${encodeURIComponent(row.slug || slug)}/`
    }));
  } else if (mode === "award-results" && results.length) {
    const winners = results.filter(row => row.vencedor);
    if (winners.length) {
      listName = `Vencedores — ${edition?.nome || `Melhores de Urânia ${year}`}`;
      listEntries = winners.slice(0, 40).map(row => ({
        name: `${row.melhores_indicados?.nome || row.melhores_indicados?.guia_comercial?.nome || "Vencedor"} (${row.melhores_categorias?.nome || "Categoria"})`,
        url: row.indicado_id ? `${DOMAIN}/melhores-de-urania/${safeYear}/vencedores/${encodeURIComponent(row.indicado_id)}/` : canonicalUrl
      }));
    }
  } else if (mode === "award-hall" && published.length) {
    const hallWinners = published.flatMap(({ edition: ed, results: edResults }) =>
      edResults.filter(row => row.vencedor).map(row => ({ ed, row }))
    );
    if (hallWinners.length) {
      listName = "Hall dos vencedores do Melhores de Urânia";
      listEntries = hallWinners.slice(0, 40).map(({ ed, row }) => ({
        name: `${row.melhores_indicados?.nome || "Vencedor"} — ${row.melhores_categorias?.nome || "Categoria"} (${ed.ano})`,
        url: row.indicado_id ? `${DOMAIN}/melhores-de-urania/${encodeURIComponent(ed.ano)}/vencedores/${encodeURIComponent(row.indicado_id)}/` : canonicalUrl
      }));
    }
  }

  const itemList = listEntries.length
    ? {
        "@type": "ItemList",
        "@id": `${canonicalUrl}#itemlist`,
        name: listName,
        numberOfItems: listEntries.length,
        itemListElement: listEntries.map((entry, index) => ({
          "@type": "ListItem",
          position: index + 1,
          name: entry.name,
          url: entry.url
        }))
      }
    : null;

  const visibleFaqKey = mode === "award-home" ? "home" : (mode === "award-edition" && edition ? "edition" : "");
  const faqNode = visibleFaqKey && FAQ_ITEMS[visibleFaqKey]
    ? {
        "@type": "FAQPage",
        "@id": `${canonicalUrl}#faq`,
        mainEntity: FAQ_ITEMS[visibleFaqKey].map(([question, answer]) => ({
          "@type": "Question",
          name: question,
          acceptedAnswer: {
            "@type": "Answer",
            text: answer
          }
        }))
      }
    : null;

  const webPage = {
    "@type": "WebPage",
    "@id": `${canonicalUrl}#webpage`,
    url: canonicalUrl,
    name: title || "Melhores de Urânia | Eu Amo Urânia",
    ...(description ? { description } : {}),
    isPartOf: { "@id": `${DOMAIN}/#website` },
    ...(image ? { primaryImageOfPage: { "@type": "ImageObject", url: image } } : {}),
    ...(itemList ? { mainEntity: { "@id": `${canonicalUrl}#itemlist` } } : {}),
    inLanguage: "pt-BR"
  };

  return {
    "@context": "https://schema.org",
    "@graph": [
      webPage,
      ...(itemList ? [itemList] : []),
      breadcrumb,
      ...(faqNode ? [faqNode] : [])
    ]
  };
}

function injectAwardsSsr(documentHtml, ssrResult) {
  if (!ssrResult?.html) return documentHtml;
  const placeholder = /<div id="awards-preview-app"><\/div>/i;
  if (!placeholder.test(documentHtml)) return documentHtml;
  const bootstrapScript = `<script id="initial-awards-data" type="application/json">${safeJson(ssrResult.bootstrap || {})}</script>`;
  return documentHtml
    .replace(placeholder, `<div id="awards-preview-app" data-server-rendered="true">${ssrResult.html}</div>`)
    .replace("</head>", `${bootstrapScript}</head>`);
}

module.exports = { renderAwardsSsr, injectAwardsSsr, resolveGuideUrl, buildGuideLookup, buildAwardStructuredData };
