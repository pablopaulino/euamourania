function renderOfficialDocument(value, fallback = "") {
  const source = String(value || fallback || "").trim();
  if (!source) return "<p>Conteúdo ainda não publicado para esta edição.</p>";
  const lines = source.split(/\n+/).map(line => line.trim()).filter(Boolean);
  const html = [];
  let list = [];
  const flushList = () => {
    if (!list.length) return;
    html.push(`<ul>${list.map(item => `<li>${esc(item.replace(/[;.]$/, ""))}</li>`).join("")}</ul>`);
    list = [];
  };
  lines.forEach((line, index) => {
    if (index === 0) { flushList(); html.push(`<h2>${esc(line)}</h2>`); return; }
    if (/^\d+\.\s+/.test(line)) { flushList(); html.push(`<h3>${esc(line)}</h3>`); return; }
    if (/^[A-ZÁÉÍÓÚÂÊÔÃÕÇ][^.!?]{2,80}:?$/.test(line) && index < 4) { flushList(); html.push(`<p class="awards-document-lead">${esc(line)}</p>`); return; }
    if (/[;]$/.test(line) || /^(Portal oficial|Enquetes oficiais|Troféu oficial|Certificado|Selo digital|Divulgação especial|Instagram:|Portal:|controle|identificação|validações|registro|auditoria|existência|enquadramento|relevância|cumprimento|revisão|integridade|votos duplicados|atividades suspeitas|inconsistências)/i.test(line)) {
      list.push(line);
      return;
    }
    flushList();
    html.push(`<p>${esc(line)}</p>`);
  });
  flushList();
  return html.join("");
}

function buildGuideLookup(guides = []) {
  const byId = new Map();
  const bySlug = new Map();
  for (const company of guides) {
    if (!company?.slug) continue;
    if (company.id) byId.set(String(company.id), company.slug);
    bySlug.set(String(company.slug), company.slug);
    if (company.nome) bySlug.set(slugify(company.nome), company.slug);
  }
  return { byId, bySlug };
}

function resolveGuideUrl(entry, lookup) {
  if (!entry) return "";
  const nominee = entry.melhores_indicados || entry;
  const embedded = nominee.guia_comercial;
  if (embedded?.slug && (!embedded.status || embedded.status === "publicado")) {
    return `/guia/${encodeURIComponent(embedded.slug)}`;
  }
  const linkedId = nominee.guia_comercial_id || nominee.empresa_id;
  if (linkedId && lookup.byId.has(String(linkedId))) {
    return `/guia/${encodeURIComponent(lookup.byId.get(String(linkedId)))}`;
  }
  const candidateSlug = nominee.slug || slugify(nominee.nome || "");
  if (candidateSlug && lookup.bySlug.has(candidateSlug)) {
    return `/guia/${encodeURIComponent(lookup.bySlug.get(candidateSlug))}`;
  }
  return "";
}

