import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import vm from "node:vm";

const source = await readFile(new URL("../admin/achados-perdidos.js", import.meta.url), "utf8");
const sql = await readFile(new URL("../supabase/migrations/20261031_admin_achados_perdidos.sql", import.meta.url), "utf8");
const scripts = source.replace(/^import .*?;\s*/m, "").replace("export async function mount", "async function mount").replace("export function unmount", "function unmount") + "\n globalThis.moduleApi = { mount, unmount };";
const listeners = {};
const container = { innerHTML: "", addEventListener: (type, fn) => listeners[type] = fn, removeEventListener: type => delete listeners[type] };
let style;
const doc = { createElement: () => (style = { dataset: {}, remove() {} }), head: { append() {} }, querySelector: () => style };
const item = { id: "11111111-1111-1111-1111-111111111111", imagem_url: "11111111-1111-1111-1111-111111111111/22222222-2222-2222-2222-222222222222.jpg", titulo: "<img onerror=alert(1)>", descricao: "<teste>", tipo: "perdido", categoria: "objeto", local: "Praça", whatsapp: "5511999999999", contato_nome: "Pessoa", atualizado_em: "2026-10-31T12:00:00.123456+00:00", criado_em: "2026-10-31T12:00:00Z" };
const calls = []; let decision = true;
const db = { storage: { from: name => { assert.equal(name, "achados-perdidos"); return { getPublicUrl: path => ({ data: { publicUrl: `https://example.org/${path}` } }) }; } }, rpc: async (name, args) => { calls.push([name, args]); return name === "admin_listar_achados_pendentes" ? { data: [item], error: null } : { data: decision, error: null }; } };
const context = { document: doc, window: { confirm: () => true }, Intl, Date, console, temPermissao: (admin, module, action) => admin.actions.includes(action) };
vm.runInNewContext(scripts, context);
await context.moduleApi.mount(container, { db, access: { admin: { actions: ["acessar", "ler", "moderar"] } } });
assert.match(container.innerHTML, /&lt;img onerror=alert\(1\)&gt;/);
assert.match(container.innerHTML, /Pessoa/); assert.match(container.innerHTML, /5511999999999/); assert.match(container.innerHTML, /<img src=/);
const button = { dataset: { id: item.id, action: "aprovar" } };
await listeners.click({ target: { closest: selector => selector === "button[data-action]" ? button : null } });
assert.equal(calls[1][0], "admin_moderar_achado"); assert.equal(calls[1][1].p_acao, "aprovar"); assert.equal(calls[1][1].p_atualizado_em, item.atualizado_em);
decision = false; button.dataset.action = "rejeitar";
await listeners.click({ target: { closest: selector => selector === "button[data-action]" ? button : null } });
assert.match(container.innerHTML, /foi alterado ou já moderado/);
context.moduleApi.unmount();
await context.moduleApi.mount(container, { db, access: { admin: { actions: ["acessar", "ler"] } } });
assert.doesNotMatch(container.innerHTML, /data-action="aprovar"/);
context.moduleApi.unmount();
assert.match(sql, /public\.is_super_admin\(\)/);
assert.match(sql, /status = 'pendente' and atualizado_em = p_atualizado_em/);
assert.doesNotMatch(sql, /insert into public\.admin_permissoes_funcao/i);
assert.match(sql, /achados_perdidos_aprovacao_push/);
console.log("Achados e Perdidos: renderização, contato, foto, permissões, decisões e concorrência validados.");
